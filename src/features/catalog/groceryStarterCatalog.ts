export function groceryCoverUrl(cover: string | null): string {
  return cover ? `/catalog/starter/abarrotes/${cover}.webp` : GENERIC_CATALOG_IMAGE;
}

export const groceryProducts: CatalogItemDefinition[] = GROCERY_CATEGORIES.flatMap((category) =>
  category.items.map(([name, price, unit]) => ({
    name,
    price,
    type: "product" as const,
    category: category.name,
    description: category.description,
    unit,
    isPublic: category.isPublic,
    imageUrl: groceryCoverUrl(category.cover),
    imageAlt: `${name}, ${category.name.toLowerCase()}`,
  })),
);
